package com.hbm.tileentity.bomb;

import com.hbm.sound.ModSounds;
import dev.golem.core.data.CompatBlockEntity;
import dev.golem.core.data.DataIn;
import dev.golem.core.data.DataOut;
import java.util.List;
import net.minecraft.core.BlockPos;
import net.minecraft.sounds.SoundSource;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.entity.MobCategory;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.phys.AABB;
import com.hbm.blocks.bomb.Landmine;
import com.hbm.tileentity.ModExplosivesBlockEntities;

/**
 * 1.7 {@code TileEntityLandmine}. After placing, the mine primes itself only once every entity has
 * left twice its trigger radius (so it does not kill the placer); a worldgen mine additionally waits
 * for a player within 25 blocks before it starts looking at mobs at all.
 */
public class TileEntityLandmine extends CompatBlockEntity {

    private boolean isPrimed = false;
    public boolean waitingForPlayer = false;

    public TileEntityLandmine(BlockPos pos, BlockState state) {
        super(ModExplosivesBlockEntities.LANDMINE.get(), pos, state);
    }

    public boolean isPrimed() {
        return isPrimed;
    }

    public static void serverTick(Level level, BlockPos pos, BlockState state, TileEntityLandmine mine) {
        if (level.isClientSide()) return;
        if (!(state.getBlock() instanceof Landmine landmine)) return;

        double range = landmine.range;
        double height = landmine.height;

        if (mine.waitingForPlayer) {
            range = 25;
            height = 25;
        } else if (!mine.isPrimed) {
            range *= 2;
            height *= 2;
        }

        if (!level.getBlockState(pos.above()).isAir()) return;

        List<Entity> list = level.getEntitiesOfClass(Entity.class, new AABB(pos.getX() - range, pos.getY() - height,
                pos.getZ() - range, pos.getX() + range + 1, pos.getY() + height, pos.getZ() + range + 1));

        for (Entity entity : list) {
            // 1.7 skips waterCreature (squid) and ambient (bats): the modern categories covering those.
            MobCategory category = entity.getType().getCategory();
            if (category == MobCategory.WATER_CREATURE || category == MobCategory.WATER_AMBIENT
                    || category == MobCategory.AMBIENT) continue;

            if (mine.waitingForPlayer) {
                // Generated by worldgen: ignore mobs until a player is close enough to make it matter.
                if (entity instanceof Player) {
                    mine.waitingForPlayer = false;
                    mine.setChanged();
                    return;
                }
            } else if (entity instanceof LivingEntity) {
                if (mine.isPrimed) {
                    // The explosion is part of the mine block so that the IBomb interface works.
                    landmine.explode(level, pos, entity);
                    // 1.7 also bumps the triggering player's statMines (no achievement stats here).
                }
                return;
            }
        }

        // Prime only once everything has left the doubled trigger radius (see class comment).
        if (!mine.isPrimed && !mine.waitingForPlayer) {
            level.playSound(null, pos, ModSounds.FSTBMB_START.get(), SoundSource.BLOCKS, 3.0F, 1.0F);
            mine.isPrimed = true;
            mine.setChanged();
        }
    }

    @Override
    protected void loadData(DataIn input) {
        isPrimed = input.getBooleanOr("primed", false);
        waitingForPlayer = input.getBooleanOr("waiting", false);
    }

    @Override
    protected void saveData(DataOut output) {
        output.putBoolean("primed", isPrimed);
        output.putBoolean("waiting", waitingForPlayer);
    }
}
