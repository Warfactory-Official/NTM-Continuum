package com.hbm.gametest;

import com.hbm.Constants;
import com.hbm.lib.ComponentIds;
import com.hbm.lib.IdConstants;
import com.hbm.lib.ItemIds;
import com.hbm.lib.TagIds;
import com.hbm.lib.VanillaIds;
import net.minecraft.gametest.framework.GameTestHelper;

import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Holds the committed id constants against the registry they were generated from.
 *
 * <p>{@link ItemIds}, {@link VanillaIds}, {@link TagIds} and {@link ComponentIds} are how a recipe
 * declaration names an ingredient, and they are generated by {@link IdConstants} out of a running
 * game and committed — the build step the declarations run in is a plain JVM that cannot load half
 * the registry classes, so it cannot derive them itself. Committed means they can go stale, and
 * stale is the one failure a compiler cannot see: the constant still compiles, and the recipe that
 * used it is dropped at load with no error, because a data pack does not refuse an ingredient it
 * cannot resolve.
 *
 * <p>So this asks the registry the same question the generator asked. What it can require of the
 * answer differs by who owns the id, because the files are generated on one node and this runs on
 * all six:
 *
 * <ul>
 *   <li><b>This mod's own ids</b> — {@code hbm:} items, components and tags — must match exactly,
 *       both ways. They are registered from the same code on every node, so a constant with nothing
 *       behind it is a rename nobody carried through, and a registered item with no constant is one
 *       the next recipe will not be able to name.
 *   <li><b>Vanilla items</b> must all have a constant, but a constant may name one this node has
 *       never heard of. Historical vanilla renames are normalized by Core in the shared roster.
 *   <li><b>Convention tags</b> are required only where this mod has an item in them. Which
 *       {@code c:} tags exist at all is up to the loader — NeoForge and Fabric API ship different
 *       sets — so that is not something one committed file can be right about everywhere.
 * </ul>
 */
public final class IdGameTests {

    private static final Map<String, Class<?>> COMMITTED = Map.of(
            "ItemIds", ItemIds.class,
            "VanillaIds", VanillaIds.class,
            "TagIds", TagIds.class,
            "ComponentIds", ComponentIds.class);

    private IdGameTests() {}

    /** The committed constants say what this node's registry says, as far as they can. */
    public static void constantsMatchTheRegistry(GameTestHelper helper) {
        List<String> problems = new ArrayList<>();
        Set<String> backed = IdConstants.backedTags();
        int checked = 0;
        int constants = 0;

        for (Map.Entry<String, Map<String, String>> family : IdConstants.rosterByClass().entrySet()) {
            String name = family.getKey();
            Map<String, String> expected = family.getValue();
            Map<String, String> committed = constants(COMMITTED.get(name));
            constants += committed.size();

            for (Map.Entry<String, String> entry : expected.entrySet()) {
                String id = entry.getValue();
                if (!required(name, id, backed)) {
                    continue;
                }
                checked++;
                String has = committed.get(entry.getKey());
                if (has == null) {
                    problems.add(name + " has no constant for " + id);
                } else if (!has.equals(id)) {
                    problems.add(name + "." + entry.getKey() + " is " + has
                            + ", but the registry says " + id);
                }
            }

            for (Map.Entry<String, String> entry : committed.entrySet()) {
                if (!owned(entry.getValue()) || expected.containsKey(entry.getKey())) {
                    continue;
                }
                problems.add(name + "." + entry.getKey() + " is " + entry.getValue()
                        + ", which this mod no longer registers");
            }
        }

        helper.assertTrue(problems.isEmpty(), join(problems)
                + " — regenerate with ./gradlew :26.1-neoforge:runGenerateIds");
        helper.assertTrue(checked > 0, "no id constants were found, so nothing was checked");
        Constants.LOG.info("[IDS] {} committed constants, {} of them required by this node's registry",
                constants, checked);
        helper.succeed();
    }

    /** Whether this node having the id means a constant has to name it. */
    private static boolean required(String family, String id, Set<String> backed) {
        // A retired vanilla tag (1.20.1's minecraft:tools, which nests minecraft:swords) is backed on an old
        // node but has no counterpart the 26.1-generated constants could carry.
        return owned(id) || "VanillaIds".equals(family)
                || backed.contains(id) && !dev.golem.core.Ids.isRetiredVanillaItemTag(id.substring(1));
    }

    /** Whether the id is this mod's own, and so the same on every node. */
    private static boolean owned(String id) {
        return id.startsWith(Constants.MOD_ID + ":") || id.startsWith("#" + Constants.MOD_ID + ":");
    }

    /** The public string constants of one generated class, keyed by field name. */
    private static Map<String, String> constants(Class<?> type) {
        Map<String, String> constants = new LinkedHashMap<>();
        for (Field field : type.getFields()) {
            if (!Modifier.isStatic(field.getModifiers()) || field.getType() != String.class) {
                continue;
            }
            try {
                constants.put(field.getName(), (String) field.get(null));
            } catch (IllegalAccessException unreachable) {
                throw new IllegalStateException(unreachable);
            }
        }
        return constants;
    }

    private static String join(List<String> problems) {
        if (problems.size() <= 8) {
            return String.join("; ", problems);
        }
        return String.join("; ", problems.subList(0, 8)) + "; and " + (problems.size() - 8) + " more";
    }
}
