package com.hbm.util;

import com.google.gson.JsonElement;
import com.hbm.api.data.HazardDataMaps;
import com.hbm.creativetabs.HbmTab;
import com.hbm.hazard.HazardSpec;
import com.hbm.hazard.HazardSystem;
import com.hbm.hazard.type.IHazardType;
import dev.golem.core.data.DataMapSource;
import dev.golem.core.world.ArmorSlot;
import dev.golem.core.world.TagSource;
import java.util.ArrayList;
import java.util.Collection;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.tags.ItemTags;
import net.minecraft.tags.TagKey;
import net.minecraft.world.item.BlockItem;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.block.Block;

/**
 * A mod's items and blocks in HBM's category tags and the convention and vanilla tags they belong to, all computed from
 * the running game by {@link TagCategories}: no item is listed by hand. An addon generates its own share with its
 * namespace; hazard types it adds are tagged on every item that carries them, since HBM's run cannot see them.
 */
public final class CategoryTagSource extends TagSource {

    /** Convention parents ({@code c:ingots}) that should hold every HBM member of their children ({@code c:ingots/lead}). */
    private static final List<String> PARENTS = List.of("ingots", "nuggets", "dusts", "gems", "ores", "storage_blocks",
            "raw_materials", "rods");

    private final String namespace;
    private final Map<String, IHazardType> ownHazards;
    private final DataMapSource<HazardSpec> hazardRows;

    /** {@code hazardRows}: the mod's rows of {@code hbm:hazards}, generated by the same run. */
    public CategoryTagSource(String namespace, Map<String, IHazardType> ownHazards, DataMapSource<HazardSpec> hazardRows) {
        this.namespace = namespace;
        this.ownHazards = ownHazards;
        this.hazardRows = hazardRows;
    }

    @Override
    protected void tags() {
        loadHazards();
        List<Item> items = new ArrayList<>();
        for (Item item : BuiltInRegistries.ITEM) if (TagCategories.isFrom(namespace, item)) items.add(item);
        List<Block> blocks = new ArrayList<>();
        for (Block block : BuiltInRegistries.BLOCK) if (TagCategories.isFrom(namespace, block)) blocks.add(block);

        item("hbm:guns", items.stream().filter(TagCategories::isGun).toList());
        item("hbm:ammo", TagCategories.ammo(namespace));
        List<Item> food = items.stream().filter(TagCategories::isFood).toList();
        item("hbm:food", food);
        item("c:foods", food);
        List<Item> armor = items.stream().filter(item -> TagCategories.armorSlot(item) != null).toList();
        item("hbm:armor", armor);
        item("c:armors", armor);
        armorSlot(armor, ArmorSlot.HELMET, "minecraft:head_armor");
        armorSlot(armor, ArmorSlot.CHESTPLATE, "minecraft:chest_armor");
        armorSlot(armor, ArmorSlot.LEGGINGS, "minecraft:leg_armor");
        armorSlot(armor, ArmorSlot.BOOTS, "minecraft:foot_armor");
        item("hbm:bombs", TagCategories.tab(HbmTab.BOMBS, namespace));
        item("hbm:missiles", TagCategories.tab(HbmTab.MISSILES, namespace));
        Set<Item> machines = TagCategories.tab(HbmTab.MACHINES, namespace);
        item("hbm:machines", machines);
        block("hbm:machines", machines.stream().filter(BlockItem.class::isInstance)
                .map(item -> ((BlockItem) item).getBlock()).toList());

        item("c:tools/melee_weapon", items.stream().filter(item -> is(item, ItemTags.SWORDS)).toList());
        item("c:tools/ranged_weapon", items.stream().filter(TagCategories::isGun).toList());
        item("c:tools/mining_tool", items.stream().filter(item -> is(item, ItemTags.PICKAXES) || is(item, ItemTags.AXES)
                || is(item, ItemTags.SHOVELS) || is(item, ItemTags.HOES)).toList());
        add("item", "c:tools", List.of("#c:tools/melee_weapon", "#c:tools/ranged_weapon", "#c:tools/mining_tool"));
        parents(items, blocks);

        hazards(items, blocks, TagCategories.HAZARDS);
        List<Item> allItems = new ArrayList<>();
        BuiltInRegistries.ITEM.forEach(allItems::add);
        List<Block> allBlocks = new ArrayList<>();
        BuiltInRegistries.BLOCK.forEach(allBlocks::add);
        hazards(allItems, allBlocks, ownHazards);
        List<String> hazardTags = new ArrayList<>();
        for (String hazard : TagCategories.HAZARDS.keySet()) hazardTags.add("#hbm:hazardous/" + hazard);
        for (String hazard : ownHazards.keySet()) hazardTags.add("#hbm:hazardous/" + hazard);
        add("item", "hbm:hazardous", hazardTags);
        add("block", "hbm:hazardous", hazardTags);

        // each tier lists the blocks that stop there and includes the next one up
        List<String> tiers = new ArrayList<>(TagCategories.BLAST_TIERS.keySet());
        for (int i = 0; i < tiers.size(); i++) {
            String tier = tiers.get(i);
            List<Block> top = blocks.stream().filter(block -> {
                Set<String> met = TagCategories.blastTiers(block);
                return !met.isEmpty() && met.stream().reduce((a, b) -> b).orElseThrow().equals(tier);
            }).toList();
            block("hbm:blast_resistant/" + tier, top);
            // every block item of the block: colours and variants may share one block
            item("hbm:blast_resistant/" + tier, items.stream()
                    .filter(item -> item instanceof BlockItem block && top.contains(block.getBlock())).toList());
            if (i + 1 < tiers.size()) {
                List<String> next = List.of("#hbm:blast_resistant/" + tiers.get(i + 1));
                add("block", "hbm:blast_resistant/" + tier, next);
                add("item", "hbm:blast_resistant/" + tier, next);
            }
        }
        add("block", "hbm:blast_resistant", List.of("#hbm:blast_resistant/" + tiers.get(0)));
        add("item", "hbm:blast_resistant", List.of("#hbm:blast_resistant/" + tiers.get(0)));

        block("hbm:radiation_shielding", blocks.stream().filter(TagCategories::shieldsRadiation).toList());
    }

    private void hazards(List<Item> items, List<Block> blocks, Map<String, IHazardType> types) {
        for (String hazard : types.keySet()) {
            item("hbm:hazardous/" + hazard, items.stream().filter(item -> TagCategories.hazards(item, types).contains(hazard)).toList());
            block("hbm:hazardous/" + hazard, blocks.stream().filter(block -> TagCategories.hazards(block, types).contains(hazard)).toList());
        }
    }

    /** The mod's hazard rows are generated by this same run, so the generating server has not loaded them: add them. */
    private void loadHazards() {
        List<JsonElement> files = new ArrayList<>();
        // the map's codec reads no registry
        for (DataMapSource.File<HazardSpec> file : hazardRows.rows().values()) files.add(hazardRows.encode(file, null));
        HazardDataMaps.HAZARDS.loadWith(files);
        HazardSystem.clearCaches();
    }

    private void armorSlot(List<Item> armor, ArmorSlot slot, String tag) {
        item(tag, armor.stream().filter(item -> TagCategories.armorSlot(item) == slot).toList());
        since("item", tag, "1.21");
    }

    /** Every member of {@code c:<parent>/<child>} also in {@code c:<parent>}, items and blocks. */
    private void parents(List<Item> items, List<Block> blocks) {
        Map<String, Set<String>> itemParents = new TreeMap<>();
        for (Item item : items) {
            item.builtInRegistryHolder().tags().forEach(tag -> {
                String parent = parent(tag.location().getNamespace(), tag.location().getPath());
                if (parent != null) itemParents.computeIfAbsent(parent, ignored -> new TreeSet<>()).add(id(item));
            });
        }
        Map<String, Set<String>> blockParents = new TreeMap<>();
        for (Block block : blocks) {
            String id = BuiltInRegistries.BLOCK.getKey(block).toString();
            block.builtInRegistryHolder().tags().forEach(tag -> {
                String parent = parent(tag.location().getNamespace(), tag.location().getPath());
                if (parent != null) blockParents.computeIfAbsent(parent, ignored -> new TreeSet<>()).add(id);
            });
        }
        itemParents.forEach((parent, members) -> add("item", "c:" + parent, members));
        blockParents.forEach((parent, members) -> add("block", "c:" + parent, members));
    }

    private static String parent(String namespace, String path) {
        if (!"c".equals(namespace)) return null;
        int slash = path.indexOf('/');
        if (slash < 0) return null;
        String parent = path.substring(0, slash);
        return PARENTS.contains(parent) ? parent : null;
    }

    private static boolean is(Item item, TagKey<Item> tag) {
        return new ItemStack(item).is(tag);
    }

    private void item(String tag, Collection<Item> items) {
        add("item", tag, items.stream().map(CategoryTagSource::id).toList());
    }

    private void block(String tag, Collection<Block> blocks) {
        add("block", tag, blocks.stream().map(block -> BuiltInRegistries.BLOCK.getKey(block).toString()).toList());
    }

    private static String id(Item item) {
        return BuiltInRegistries.ITEM.getKey(item).toString();
    }
}
